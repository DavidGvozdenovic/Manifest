const DICT: Record<Locale, typeof EN> = { en: EN, sr: SR };

export type MessageKey = keyof typeof EN;

export function t(locale: Locale, key: MessageKey) {
  return DICT[locale][key];
}

export function ppiLabel(locale: Locale, ppi: 72 | 150 | 300) {
  if (ppi === 72) return t(locale, 'ppiScreen');
  if (ppi === 150) return t(locale, 'ppiLarge');
  return t(locale, 'ppiClose');
}
